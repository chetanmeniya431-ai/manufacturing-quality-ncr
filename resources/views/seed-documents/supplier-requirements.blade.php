<h1>Supplier Quality Requirements — Revision 4</h1>
<p>Document ref: SQR-VPP-04. This document defines the minimum quality requirements that all approved
suppliers to Vantage Precision Parts Ltd must meet as a condition of supply.</p>

<h2>1. Approval to Supply</h2>
<p>Only suppliers listed as "approved" in the Vantage Precision Parts Ltd supplier register may ship
product. Approval requires a completed supplier quality questionnaire, evidence of an ISO 9001
certified quality system (or equivalent), and a satisfactory first-article inspection result.</p>

<h2>2. Certificates of Conformance</h2>
<p>Every shipment must include a Certificate of Conformance (CoC) referencing the purchase order,
material or part specification revision, batch or heat number, and quantity. Material suppliers must
also provide a mill certificate showing chemical composition and mechanical properties.</p>

<h2>3. Non-Conformance and Corrective Action</h2>
<p>Where a supplied part or material is found non-conforming, Vantage Precision Parts Ltd will log an
NCR with defect category "Supplier defect" and issue a Supplier Corrective Action Request (SCAR) to
the responsible supplier. The supplier must respond within 5 working days with containment action,
and within 15 working days with root cause and permanent corrective action, using an 8D or equivalent
format. Failure to respond within these windows will be recorded against the supplier's quality
score and may result in suspension of approved status.</p>

<h2>4. Quality Score and Monitoring</h2>
<p>Vantage Precision Parts Ltd calculates a rolling quality score for every supplier based on
non-conformances recorded within the trailing 90 days: minus 5 points per Minor non-conformance,
minus 15 points per Major non-conformance, and minus 30 points per Critical non-conformance. The
score recovers by 1 point per week with no new non-conformances. Suppliers scoring below 60 are
placed on quality watch with increased incoming inspection (100% sampling) until the score recovers
above 80 for a sustained period. Suppliers causing 3 or more non-conformances within any 60-day
window are subject to an on-site supplier audit at Vantage's discretion.</p>

<h2>5. Change Notification</h2>
<p>Suppliers must notify Vantage Precision Parts Ltd in writing at least 30 days in advance of any
change to material source, manufacturing process, manufacturing location, or sub-tier supplier that
could affect form, fit, or function of the supplied product. Unauthorized changes discovered after
the fact will be treated as a non-conformance regardless of whether the delivered product otherwise
conforms to specification.</p>

<h2>6. Record Retention</h2>
<p>Suppliers must retain inspection records, certificates of conformance, and traceability records for
a minimum of seven years, matching Vantage Precision Parts Ltd's own NCR and quality document
retention policy under ISO 9001:2015 clause 7.5.3.</p>
