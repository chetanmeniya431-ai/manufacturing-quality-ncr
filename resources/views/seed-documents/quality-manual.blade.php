<h1>Vantage Precision Parts Ltd — ISO 9001:2015 Quality Manual (Excerpt)</h1>
<p>Document ref: QM-VPP-01, Revision 6. This manual defines the quality management system (QMS) of
Vantage Precision Parts Ltd, an ISO 9001:2015 certified manufacturer of precision machined automotive
components, covering incoming inspection, in-process control, final inspection, non-conformance
management, corrective and preventive action (CAPA), supplier quality, and internal audit.</p>

<h2>1. Scope and Context</h2>
<p>This QMS applies to all design, machining, finishing, inspection, and dispatch activities carried out
at the Vantage Precision Parts Ltd facility. It applies to all permanent staff, contract staff, and
approved suppliers providing product or process-affecting services.</p>

<h2>2. Non-Conformance Management</h2>
<p>Any product, process, or material that does not meet a specified requirement shall be recorded as a
Non-Conformance Report (NCR). NCRs are logged with a unique NCR number in the format NCR-YYYY-NNNN,
and progress through a fixed workflow: Open, Under Investigation, Corrective Action Assigned,
Verification, and Closed. Each stage change is recorded with the responsible person and timestamp.
An NCR may not skip a stage or move backward once advanced.</p>
<p>Severity is classified as Minor, Major, or Critical. Minor non-conformances are isolated defects with
no functional impact. Major non-conformances affect fit, form, or function of the product but do not
present an immediate safety risk. Critical non-conformances present a safety, regulatory, or
significant customer-impact risk and require immediate containment action within 24 hours of
detection.</p>

<h2>3. Corrective and Preventive Action (CAPA) Requirement</h2>
<p>A documented Corrective Action Plan (CAPA) is mandatory for every Major and Critical non-conformance.
The CAPA must identify the root cause using a structured method (5-Why or fishbone analysis), define
the corrective action, assign an owner and due date, and be verified effective before the NCR is
closed. Minor non-conformances may be closed with a documented root cause and correction, but a full
CAPA is only mandatory when a Minor defect recurs three or more times within a rolling 30-day window,
at which point it is treated as a systemic issue requiring full CAPA treatment.</p>
<p>Closure of any NCR — regardless of severity — requires a closure note and explicit confirmation that
the corrective action has been verified effective. Verification evidence (measurement data, re-test
results, or process audit) must be attached or referenced in the closure note.</p>

<h2>4. Root Cause Analysis</h2>
<p>Root cause analysis shall consider material, machine, method, measurement, environment, and personnel
factors (the 6M framework). Where a similar non-conformance has occurred previously, the investigator
should review closed NCRs with matching product, defect category, or description for a likely shared
root cause before concluding the investigation.</p>

<h2>5. Record Retention</h2>
<p>All NCR records, including investigation notes, corrective action evidence, and closure
documentation, must be retained for a minimum of seven (7) years from the date of closure, in line
with ISO 9001:2015 clause 7.5.3 and applicable automotive customer requirements (IATF 16949
alignment). Quality documents such as this manual, product specifications, and supplier quality
requirements must be retained for the life of the associated product program plus seven years.</p>

<h2>6. Supplier Quality Management</h2>
<p>All suppliers are maintained in the supplier register with an approval status and a quality score.
The quality score starts at 100 points and is reduced by 5 points for each Minor non-conformance,
15 points for each Major non-conformance, and 30 points for each Critical non-conformance recorded
against that supplier within the trailing 90 days. The score recovers by 1 point per week in which no
new non-conformance is recorded against that supplier. A supplier whose score falls below 60 is
placed on quality watch: incoming inspection sampling is increased to 100% and a supplier corrective
action request (SCAR) is issued. A supplier who causes three or more non-conformances within any
rolling 60-day window is considered a repeat-failure supplier and is subject to a supplier audit.</p>

<h2>7. Signals and Escalation</h2>
<p>The quality system automatically monitors for the following conditions and raises a signal when
detected: an Open NCR not moved to Under Investigation within 3 days; an NCR remaining in Corrective
Action Assigned status for 14 or more days; the same defect category occurring 5 or more times within
30 days; the same product having 3 or more NCRs within 30 days; a supplier quality score dropping
below 60; a Critical NCR remaining open for more than 24 hours without a status change; a supplier
causing 3 or more NCRs within 60 days; an NCR remaining in Verification for 7 or more days; any NCR
where the non-conformance was detected via a customer return; and a month-over-month spike in total
NCR volume of 50% or more. Each signal is reviewed by the Quality Manager and either actioned or
formally resolved.</p>

<h2>8. Incoming, In-Process, and Final Inspection</h2>
<p>Incoming inspection verifies supplied material and components against the applicable purchase
specification before release to production. In-process inspection is performed at defined hold
points during machining and finishing. Final inspection verifies the completed part against the
approved product specification before release to dispatch. Non-conformances found at any of these
three stages, or reported back by a customer after delivery ("customer return"), are all logged
using the same NCR process described above.</p>

<h2>9. Internal Audit and Management Review</h2>
<p>Internal audits are conducted quarterly against this manual and the applicable ISO 9001:2015
clauses. Audit findings that identify a non-conformance are logged as NCRs using the standard
process. Management review is conducted at least twice per year and includes a review of NCR trends,
supplier quality scores, open signal events, and the effectiveness of prior corrective actions.</p>
