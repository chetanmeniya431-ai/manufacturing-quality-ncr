<p>Any dimension found outside the tolerance band above shall be logged as an NCR with defect category
"Dimension out of spec." Parts outside tolerance may not be reworked without an approved deviation
from Engineering.</p>

<h2>3. Surface Finish Requirements</h2>
<p>Surface roughness on the bearing journal and spline contact surfaces shall not exceed Ra 0.8
micrometres, measured per ISO 4287 using a calibrated profilometer, with three readings taken at 120
degree intervals around the circumference. Surface roughness on non-functional turned surfaces shall
not exceed Ra 3.2 micrometres. Any surface exceeding these acceptance criteria shall be logged as an
NCR with defect category "Surface defect." Surface defects visible to the naked eye — including
tool marks, chatter, burns, or corrosion — are non-conforming regardless of measured Ra value.</p>

<h2>4. Heat Treatment and Hardness</h2>
<p>Case hardness on the spline teeth shall be 58-62 HRC to a case depth of 0.8-1.2 mm. Core hardness
shall be 28-32 HRC. Hardness verification is required on one part per heat-treatment batch using a
Rockwell hardness tester, with the result recorded on the batch traveler.</p>

<h2>5. Inspection Plan</h2>
<p>100% dimensional inspection is required on the bearing journal diameter and spline major diameter
for every part. Sample inspection (skip-lot, 1-in-10) is permitted for overall length and keyway
width once process capability (Cpk &ge; 1.33) has been demonstrated and approved by the Quality
Manager. Surface roughness is verified on a 1-in-20 sample basis unless a supplier or process change
has occurred, in which case 100% inspection resumes for the first 50 parts.</p>

<h2>6. Packaging and Traceability</h2>
<p>Each shipment must be accompanied by a batch traveler recording heat number, machine ID, operator,
and inspection results. Parts must be packaged to prevent corrosion and mechanical damage in transit,
with desiccant included for shipments exceeding 14 days transit time.</p>

<h2>7. Approved Suppliers</h2>
<p>Bar stock for this part may be sourced only from suppliers listed as "approved" in the supplier
register with product category "alloy steel bar stock." Any non-conformance traced to supplied
material shall be logged with defect category "Supplier defect" and linked to the responsible
supplier record so the supplier's quality score reflects the failure.</p>
