<h1>Product Specification — Precision Shaft Type A</h1>
<p>Document ref: PS-PSA-04, Revision 3. This specification defines the dimensional, material, and
surface finish requirements for Precision Shaft Type A, an automotive transmission input shaft
machined from EN24T alloy steel bar stock.</p>

<h2>1. Material</h2>
<p>Material shall be EN24T (817M40) alloy steel, supplied hardened and tempered to 28-32 HRC unless
otherwise specified on the drawing. Material certification (mill certificate) must accompany each
batch and be retained with the incoming inspection record.</p>

<h2>2. Dimensional Requirements</h2>
